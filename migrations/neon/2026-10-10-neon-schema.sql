-- ---------- v0.7.0 的兩個函式（與 Supabase 線上一致） ----------
create or replace function public.dict_entry_counts(unit_ids bigint[])
returns table (unit_id bigint, status text, n integer)
language sql
stable
as $$
    select e.unit_id, e.status, count(*)::int as n
    from public.dict_entries e
    where unit_ids is null or e.unit_id = any(unit_ids)
    group by e.unit_id, e.status;
$$;

create or replace function public.dict_db_size()
returns bigint
language sql
stable
as $$
    select pg_database_size(current_database())::bigint;
$$;

