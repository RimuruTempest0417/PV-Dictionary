-- v0.8.0（Neon 影子驗證）：Neon 版的 schema
--
-- 為什麼要另寫一份、而不是直接貼 migrations/*.sql：
--   1. Supabase 的遷移檔裡有 `revoke all on ... from anon, authenticated` —— 這兩個角色是 Supabase
--      才有的，**Neon 沒有這兩個角色**，直接貼會 `role "anon" does not exist` 而中斷。
--   2. 這裡改成對 `public` 撤銷權限（每個 Postgres 都有），效果相同：只有專案擁有者／
--      我們自己發的 JWT 角色能碰這些表。
--   3. 其餘（表、欄位、索引、函式）刻意與 Supabase 版**完全一致**，影子驗證才有意義。
--
-- 執行方式：`connectors__neon_mcp__RUN_SQL_TRANSACTION`（或貼進 Neon SQL Editor），整份 idempotent。
-- 目標專案：Gary-dictionary（`still-dawn-90059323`，region `aws-ap-southeast-1`）。

-- ---------- 書本 ----------
create table if not exists public.dict_books (
    id            bigint generated by default as identity primary key,
    code          text not null unique,
    name          text not null,
    grade         text,
    publisher     text,
    sort_order    int not null default 0,
    is_published  boolean not null default true,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz
);

-- ---------- 單元 ----------
create table if not exists public.dict_units (
    id           bigint generated by default as identity primary key,
    book_id      bigint not null references public.dict_books(id) on delete cascade,
    unit_no      int not null,
    title        text,
    sort_order   int not null default 0,
    is_published boolean not null default true,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz,
    unique (book_id, unit_no)
);

-- ---------- 生字 ----------
create table if not exists public.dict_entries (
    id             bigint generated by default as identity primary key,
    unit_id        bigint not null references public.dict_units(id) on delete cascade,
    headword       text not null,
    headword_norm  text not null,
    ipa_us         text,
    ipa_uk         text,
    part_of_speech text,
    zh_meaning     text,
    en_definition  text,
    example_en     text,
    example_zh     text,
    status         text not null default 'published',
    review_note    text,
    reviewed_by    text,
    reviewed_at    timestamptz,
    sort_order     int not null default 0,
    created_by     text,
    updated_by     text,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz,
    unique (unit_id, headword_norm)
);

-- ---------- 老師錄音 ----------
create table if not exists public.dict_audio (
    id          bigint generated by default as identity primary key,
    entry_id    bigint not null references public.dict_entries(id) on delete cascade,
    source      text not null default 'teacher',
    accent      text,
    mime        text not null,
    bytes       int not null,
    duration_ms int,
    data        text not null,
    uploaded_by text,
    created_at  timestamptz not null default now()
);

-- ---------- 使用者 ----------
create table if not exists public.dict_users (
    id            bigint generated by default as identity primary key,
    username      text not null unique,
    display_name  text,
    password_hash text not null,
    role          text not null default 'student',
    is_active     boolean not null default true,
    last_login_at timestamptz,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz
);

-- ---------- 單元級授權 ----------
create table if not exists public.dict_grants (
    id          bigint generated by default as identity primary key,
    user_id     bigint not null,
    book_id     bigint,
    unit_id     bigint,
    can_edit    boolean not null default true,
    can_publish boolean not null default false,
    granted_by  text,
    created_at  timestamptz not null default now()
);

-- ---------- 稽核 ----------
create table if not exists public.dict_audit_logs (
    id           bigint generated by default as identity primary key,
    user_id      text,
    display_name text,
    role         text,
    action       text not null,
    target_id    text,
    details      text,
    ip           text,
    created_at   timestamptz not null default now()
);

-- ---------- 錯誤日誌（不進 hydrate 快取） ----------
create table if not exists public.dict_error_logs (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    source text not null default 'client',
    level text not null default 'error',
    code text not null default '',
    message text not null default '',
    path text not null default '',
    version text not null default '',
    user_id bigint,
    display_name text not null default '',
    user_agent text not null default '',
    is_self_test boolean not null default false,
    context jsonb,
    resolved boolean not null default false,
    resolved_by bigint,
    resolved_at timestamptz,
    resolved_note text not null default ''
);

